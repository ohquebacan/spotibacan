void lang_set(lang_id id)
{
	if (id >= 0 && id < LANG_COUNT)
		s_lang = id;
}

lang_id lang_get(void)
{
	return s_lang;
}

const char *tr(str_id id)
{
	if (id < 0 || id >= S_COUNT)
		return "";
	const char *s = s_strings[s_lang][id];
	return s ? s : "";
}
